function setLanguage(lang) {
    const data = translations[lang];
    
    // Set Document Direction
    document.documentElement.setAttribute('dir', data.dir);
    document.documentElement.setAttribute('lang', lang);

    // Active button state & dynamic color changes
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.className = 'lang-btn';
    });

    const activeBtn = document.getElementById(`btn-${lang}`);
    if (activeBtn) {
        activeBtn.classList.add(`active-${lang}`);
    }

    // Text Updates
    document.getElementById('main-title').innerText = data.mainTitle;
    document.getElementById('main-subtitle').innerText = data.mainSubtitle;
    
    // Offer texts
    document.getElementById('offer-badge-text').innerText = data.offerBadge;
    document.getElementById('offer-main-title').innerText = data.offerTitle;
    document.getElementById('offer-main-sub').innerText = data.offerSub;
    document.getElementById('lbl-old-price').innerText = data.lblOldPrice;
    document.getElementById('lbl-new-price').innerText = data.lblNewPrice;
    document.getElementById('lbl-currency').innerText = data.lblCurrency;

    document.getElementById('course-link-title').innerText = data.courseTitle;
    document.getElementById('course-link-sub').innerText = data.courseSub;
    document.getElementById('btn-text-1').innerText = data.btnGo;
    document.getElementById('sec-suitable-title').innerText = data.secSuitable;
    document.getElementById('sec-learn-title').innerText = data.secLearn;
    document.getElementById('feature-description').innerHTML = data.feature;
    document.getElementById('sec-contact-title').innerText = data.secContact;
    document.getElementById('btn-text-2').innerText = data.btnMsg;
    document.getElementById('wa-subtitle').innerText = data.waSub;
    document.getElementById('btn-text-wa-chat').innerText = data.btnWaChat;
    document.getElementById('btn-text-wa-call').innerText = data.btnWaCall;
    document.getElementById('footer-text').innerText = data.footerText;

    // Arrow direction handling
    const arrowIcons = document.querySelectorAll('.arrow-icon');
    arrowIcons.forEach(icon => {
        if (data.dir === 'ltr') {
            icon.className = 'fa-solid fa-arrow-right arrow-icon';
        } else {
            icon.className = 'fa-solid fa-arrow-left arrow-icon';
        }
    });

    // List Updates
    const suitableContainer = document.getElementById('suitable-list');
    suitableContainer.innerHTML = data.suitable.map(item => `<div class="grid-item">${item}</div>`).join('');

    const learnContainer = document.getElementById('learn-list');
    learnContainer.innerHTML = data.learn.map(item => `<div class="grid-item">${item}</div>`).join('');
}

// Initial call
document.addEventListener('DOMContentLoaded', () => {
    setLanguage('ckb');
});